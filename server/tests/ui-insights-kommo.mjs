// Insights no navegador: Gerencial (Painel), Relatórios (4 abas) e Atividades (registro de eventos),
// botão por botão. API 3011 + front 5183 + seed + seed-kommo-estrutura.
import { chromium } from 'playwright-core'

const CHROME = process.env.CHROME || 'C:/Program Files/Google/Chrome/Application/chrome.exe'
const OUT = process.env.OUT || '.'
const browser = await chromium.launch({ executablePath: CHROME, headless: true })
const page = await browser.newPage({ viewport: { width: 1366, height: 860 } })
const errors = []
page.on('pageerror', e => errors.push('pageerror: ' + e.message))
page.on('console', m => { if (m.type() === 'error' && !/Failed to load resource/.test(m.text())) errors.push('console: ' + m.text()) })
let ok = 0, fail = 0
const check = (n, c) => { c ? ok++ : fail++; console.log(c ? '  ✓' : '  ✗', n) }
const api = (path, opts = {}) => page.evaluate(async ([p, o]) => { const r = await fetch('http://localhost:3011' + p, { ...o, headers: { 'Content-Type': 'application/json', Authorization: localStorage.getItem('auth_token') } }); return r.status === 204 ? null : r.json() }, [path, opts])
const waitApi = (part) => page.waitForResponse(r => r.url().includes(part) && r.status() === 200, { timeout: 8000 }).catch(() => null)

await page.goto('http://localhost:5183/login'); await page.fill('#email', 'diretoria@teste.local'); await page.fill('#password', '123456')
await page.getByRole('button', { name: 'Login', exact: true }).click(); await page.waitForURL('**/dashboard')

console.log('Gerencial (Painel)')
await page.locator('.app-sidebar').getByRole('button', { name: 'Insights' }).click()
await page.locator('.app-sidebar').getByRole('button', { name: 'Gerencial' }).click()
await page.getByRole('heading', { name: 'Clara Ferreira' }).waitFor()
check('menu Insights › Gerencial abre o painel', page.url().endsWith('/gerencial'))
const blocos = ['Mensagens recebidas', 'Conversas em andamento', 'Conversas não respondidas', 'Tempo de resposta', 'Mais tempo esperando', 'Fontes de lead', 'Leads ganhos', 'Leads ativos', 'Leads perdidos', 'Leads sem tarefas', 'Tarefas']
for (const b of blocos) check(`bloco "${b}"`, await page.getByRole('region', { name: b, exact: true }).isVisible())
for (const [label, period] of [['Hoje', 'today'], ['Ontem', 'yesterday'], ['Mês', 'month'], ['Semana', 'week']]) {
  const w = waitApi(`/insights/painel?period=${period}`)
  await page.getByRole('group', { name: 'Período' }).getByRole('button', { name: label, exact: true }).click()
  check(`período "${label}" recarrega o painel`, !!(await w) && (await page.getByRole('button', { name: label, exact: true }).getAttribute('aria-pressed')) === 'true')
}
let w = waitApi('/insights/painel?period=custom')
await page.getByRole('button', { name: /Período/ }).click()
await page.getByLabel('De', { exact: true }).fill('2026-10-01'); await page.getByLabel('Até', { exact: true }).fill('2026-10-20')
check('"Período" com datas consulta o intervalo', !!(await w))
await page.getByRole('group', { name: 'Período' }).getByRole('button', { name: 'Semana', exact: true }).click()
w = waitApi('user_id=')
await page.getByLabel('Selecionar usuário').selectOption({ label: 'Diana Diretoria' })
check('filtro de usuário', !!(await w))
await page.getByRole('button', { name: 'Todos', exact: true }).click()
await page.locator('.k-painel').getByRole('button', { name: 'Configurações' }).click()
const dlg = page.getByRole('dialog', { name: 'Configurações do painel' })
await dlg.getByLabel('Fontes de lead').uncheck()
check('Configurações esconde um bloco', !(await page.getByRole('region', { name: 'Fontes de lead' }).isVisible()))
await dlg.getByLabel('Fontes de lead').check(); await dlg.getByTitle('Fechar').click()
check('Configurações mostra de novo', await page.getByRole('region', { name: 'Fontes de lead' }).isVisible())
await page.screenshot({ path: OUT + '/ins-gerencial.png' })
await page.getByRole('region', { name: 'Conversas em andamento' }).click(); await page.waitForURL('**/conversas')
check('clicar em "Conversas em andamento" abre Conversas', page.url().endsWith('/conversas'))
await page.goto('http://localhost:5183/gerencial'); await page.locator('.k-painel').getByRole('button', { name: 'ATIVIDADES' }).click(); await page.waitForURL('**/atividades')
check('botão ATIVIDADES abre o registro', page.url().endsWith('/atividades'))

console.log('Relatórios')
await page.locator('.app-sidebar').getByRole('button', { name: 'Relatórios' }).click(); await page.waitForURL('**/relatorios'); await page.getByRole('tablist').first().waitFor()
for (const t of ['Análise de vendas', 'Relatório consolidado', 'Relatório de atividades', 'Relatório de meta']) check(`aba "${t}"`, await page.getByRole('tab', { name: t }).isVisible())
await page.locator('[data-testid="vendas-etapa"]').first().waitFor()
check('Análise de vendas mostra as etapas do funil', (await page.locator('[data-testid="vendas-etapa"]').count()) >= 3 && await page.getByText('Funil de conversão').isVisible() && await page.getByText('Motivos de perda').isVisible())
const pipes = await api('/pipelines'); const onb = pipes.find(p => p.slug === 'onboarding')
w = waitApi(`pipeline_id=${onb.id}`)
await page.getByLabel('Funil').selectOption(String(onb.id))
check('trocar o funil recarrega a análise', !!(await w) && await page.getByText(`Leads · ${onb.name}`).isVisible())
await page.getByRole('button', { name: 'Filtro' }).click()
check('botão Filtro esconde a barra de filtros', !(await page.getByLabel('Funil').isVisible()))
await page.getByRole('button', { name: 'Filtro' }).click()
await page.screenshot({ path: OUT + '/ins-vendas.png' })

await page.getByRole('tab', { name: 'Relatório consolidado' }).click()
await page.getByRole('tab', { name: 'SEMANA' }).waitFor()
check('aba consolidado: DIA / SEMANA / MÊS, estágios e usuários', await page.getByText('Estágios do funil de vendas').isVisible() && await page.getByText('Leads por usuário').isVisible())
w = waitApi('group=week'); await page.getByRole('tab', { name: 'SEMANA' }).click()
check('agrupar por semana', !!(await w))
check('URL guarda a aba', page.url().includes('aba=consolidado'))

await page.getByRole('tab', { name: 'Relatório de atividades' }).click()
await page.locator('[data-testid="ativ-linha"]').first().waitFor()
const cols = (await page.locator('th').allInnerTexts()).map(t => t.trim().toLowerCase())
check('relatório de atividades com as colunas do Kommo', ['nome', 'leads em processo', 'notas adicionadas', 'total de tarefas', 'vendas totais'].every(c => cols.includes(c)))
w = waitApi('/insights/atividades'); await page.getByLabel('Selecionar usuário').selectOption({ label: 'Diana Diretoria' }); await w
await page.waitForTimeout(300)
check('filtrar usuário deixa 1 linha', (await page.locator('[data-testid="ativ-linha"]').count()) === 1)
await page.getByRole('button', { name: 'Todos', exact: true }).click()

await page.getByRole('tab', { name: 'Relatório de meta' }).click()
await page.getByRole('button', { name: 'Definir metas' }).waitFor()
check('relatório de meta: Total + Seção de vendas', await page.getByText('Seção de vendas').isVisible() && (await page.locator('[data-testid="meta-linha"]').count()) >= 3)
await page.getByRole('button', { name: 'Definir metas' }).click()
await page.getByLabel('Meta em R$ de Diana Diretoria').fill('3000'); await page.getByLabel('Nº de vendas de Diana Diretoria').fill('6')
await page.getByRole('button', { name: 'Salvar' }).click(); await page.waitForTimeout(800)
const metas = await api('/insights/metas'); const md = metas.usuarios.find(u => u.nome === 'Diana Diretoria')
check('Definir metas salva no banco', md.meta_valor === 3000 && md.meta_qtd === 6)
check('barra da Diana mostra a meta', await page.getByText(/de R\$\s?3\.000,00/).first().waitFor({ timeout: 5000 }).then(() => true, () => false))
await page.getByRole('button', { name: 'Por quantidade' }).click()
check('"Por quantidade" troca para nº de vendas', await page.getByText(/de 6 ·/).first().isVisible())
await page.screenshot({ path: OUT + '/ins-metas.png' })
await api('/insights/metas', { method: 'PUT', body: JSON.stringify({ month: metas.month, metas: [{ user_id: md.user_id, meta_valor: 0, meta_qtd: 0 }] }) })

console.log('Atividades (registro de eventos)')
await page.locator('.app-sidebar').getByRole('button', { name: 'Atividades' }).click(); await page.waitForURL('**/atividades')
await page.locator('[data-testid="evento"]').first().waitFor()
const cols2 = (await page.locator('th').allInnerTexts()).map(t => t.trim().toLowerCase())
check('colunas DATA · USUÁRIO · TIPO DE OBJETO · NOME DO OBJETO · ATIVIDADES · VALOR ANTES · VALOR DEPOIS', ['data', 'usuário', 'tipo de objeto', 'nome do objeto', 'atividades', 'valor antes', 'valor depois'].every(c => cols2.includes(c)))
await page.getByLabel('Filtro', { exact: true }).click()
const fd = page.getByRole('dialog', { name: 'Filtro de eventos' })
check('clicar no Filtro abre o painel', await fd.isVisible())
await fd.getByLabel('Tipo de objeto').selectOption('tarefa')
w = waitApi('object_type=tarefa'); await fd.getByRole('button', { name: 'Aplicar' }).click(); await w; await page.waitForTimeout(300)
const tipos = await page.locator('[data-testid="evento"] td:nth-child(3)').allInnerTexts()
check('filtro "Tarefa" só mostra tarefas', tipos.length > 0 && tipos.every(t => t === 'Tarefa'))
check('filtro ativo aparece como etiqueta', await page.locator('.k-topbar').getByText('Tarefa', { exact: true }).isVisible())
await page.getByLabel('Filtro', { exact: true }).click()
await fd.getByLabel('Conclusão da tarefa').check()
w = waitApi('event_type=task_completed'); await fd.getByRole('button', { name: 'Aplicar' }).click(); await w; await page.waitForTimeout(300)
const evs = await page.locator('[data-testid="evento"] td:nth-child(5)').allInnerTexts()
check('filtro de evento "Conclusão da tarefa"', evs.length > 0 && evs.every(t => t === 'Conclusão da tarefa'))
await page.getByLabel('Filtro', { exact: true }).fill('nada-com-esse-nome-xyz'); await page.keyboard.press('Enter'); await page.waitForTimeout(700)
check('busca sem resultado mostra a mensagem do Kommo', await page.getByText('Desculpe, não há eventos com esses parâmetros.').isVisible())
await page.getByRole('button', { name: 'Mostrar tudo' }).click(); await page.waitForTimeout(700)
check('"Mostrar tudo" limpa o filtro', (await page.locator('[data-testid="evento"]').count()) > 0)
await page.getByLabel('Filtro', { exact: true }).click()
await fd.getByLabel('Usuário').selectOption('robo')
w = waitApi('user_id=robo'); await fd.getByRole('button', { name: 'Aplicar' }).click(); await w; await page.waitForTimeout(300)
const us = await page.locator('[data-testid="evento"] td:nth-child(2)').allInnerTexts()
check('filtro "Robô" mostra só automações', us.every(t => t === 'Robô'))
await page.getByTitle('Limpar filtro').click(); await page.waitForTimeout(600)
w = waitApi('per=10'); await page.getByLabel('Mostrar linhas').selectOption('10'); await w; await page.waitForTimeout(300)
check('"Mostrar linhas: 10"', (await page.locator('[data-testid="evento"]').count()) <= 10)
const total = (await api('/insights/eventos?per=10')).has_more
if (total) {
  w = waitApi('page=2'); await page.getByTitle('Próxima página').click(); await w; await page.waitForTimeout(300)
  check('próxima página', (await page.getByLabel('Página').innerText()) === '2')
  await page.keyboard.press('Control+ArrowLeft'); await page.waitForTimeout(600)
  check('Ctrl ← volta a página', (await page.getByLabel('Página').innerText()) === '1')
} else { check('paginação (poucos eventos, setas desativadas)', await page.getByTitle('Próxima página').isDisabled()) }
await page.getByLabel('Mostrar linhas').selectOption('50')
await page.screenshot({ path: OUT + '/ins-atividades.png' })
const nome = page.locator('[data-testid="evento"] td:nth-child(4) button').first()
if (await nome.count()) { await nome.click(); await page.waitForURL(/\/contatos\/\d+/); check('nome do objeto abre o contato', /\/contatos\/\d+/.test(page.url())) }

console.log('Celular (390 px)')
await page.setViewportSize({ width: 390, height: 800 })
for (const u of ['/gerencial', '/relatorios', '/relatorios?aba=metas', '/atividades']) {
  await page.goto('http://localhost:5183' + u); await page.waitForTimeout(1500)
  const over = await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)
  check(`${u} sem rolagem lateral no celular`, over <= 1)
}
await page.goto('http://localhost:5183/gerencial'); await page.waitForTimeout(1200); await page.screenshot({ path: OUT + '/ins-gerencial-cel.png', fullPage: true })

console.log(errors.length ? '\nErros no console:\n' + errors.join('\n') : '\nsem erros no console')
console.log(`${ok} ok, ${fail} falha(s)`)
await browser.close()
process.exit(fail ? 1 : 0)
